CREATE TABLE IF NOT EXISTS village (id INTEGER PRIMARY KEY, lv INTEGER NOT NULL DEFAULT 0, wood INTEGER NOT NULL DEFAULT 0, stone INTEGER NOT NULL DEFAULT 0, gold INTEGER NOT NULL DEFAULT 0, live_until INTEGER NOT NULL DEFAULT 0, at INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO village (id) VALUES (1);
CREATE TABLE IF NOT EXISTS village_give (user_id INTEGER PRIMARY KEY, score REAL NOT NULL DEFAULT 0, at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS village_give_score ON village_give(score);
CREATE TABLE IF NOT EXISTS chronicle (id INTEGER PRIMARY KEY AUTOINCREMENT, at INTEGER NOT NULL, kind TEXT NOT NULL, text TEXT NOT NULL);
